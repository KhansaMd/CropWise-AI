"""Export the climate data into a Next.js app (App Router) so Vercel serves the same endpoints with no Python.

  python scripts/export_next.py --next-dir ../frontend

It writes, inside the Next.js app:
  <src>/climate-data/climate/<region>.json          daily series + baseline (4 files)
  <src>/climate-data/summary/<region>.<season>.json seasonal summaries (12 files)
  <src>/climate-data/regions.json
  <src>/climate-data/index.ts                       typed imports of all of the above
  <src>/app/api/regions/route.ts                    GET /api/regions
  <src>/app/api/climate/route.ts                    GET /api/climate?region=&start=&end=&baseline=
  <src>/app/api/climate/summary/route.ts            GET /api/climate/summary?region=&season=

Differences from the FastAPI version: the summary is always the latest complete season
(`year` and `include_partial` are rejected). Re-run this script after every new ingest.
Existing route.ts files are not overwritten unless you pass --force.
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

for _name in ("cropwise_climate", "fieldshift"):
    try:
        climate = importlib.import_module(f"{_name}.climate")
        _settings = importlib.import_module(f"{_name}.settings")
        _store = importlib.import_module(f"{_name}.store")
        break
    except ModuleNotFoundError as exc:
        if exc.name != _name:
            raise
else:
    raise SystemExit("Could not import the backend package (cropwise_climate). Run from the backend folder.")

load_regions, load_settings = _settings.load_regions, _settings.load_settings
CacheMissing, load_cache = _store.CacheMissing, _store.load_cache

HEADER = "// GENERATED by scripts/export_next.py. Do not edit by hand; re-run the script.\n"

ROUTE_REGIONS = HEADER + """import { regions } from "__REL__";

export async function GET() {
  return Response.json(regions, {
    headers: { "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400" },
  });
}
"""

ROUTE_CLIMATE = HEADER + """import { climate } from "__REL__";

const DATE = /^\\d{4}-\\d{2}-\\d{2}$/;

export async function GET(request: Request) {
  const sp = new URL(request.url).searchParams;
  const region = sp.get("region") ?? "";
  const data = climate[region];
  if (!data) {
    return Response.json(
      { detail: `Unknown region '${region}'. Known: ${Object.keys(climate).join(", ")}` },
      { status: 404 },
    );
  }
  const start = sp.get("start");
  const end = sp.get("end");
  for (const [key, value] of [["start", start], ["end", end]] as const) {
    if (value !== null && !DATE.test(value)) {
      return Response.json({ detail: `${key} must be YYYY-MM-DD` }, { status: 422 });
    }
  }
  let series = data.series as Array<{ date: string }>;
  if (start) series = series.filter((row) => row.date >= start);
  if (end) series = series.filter((row) => row.date <= end);
  if (series.length === 0) {
    return Response.json({ detail: "No data in that date range." }, { status: 422 });
  }
  const body: Record<string, unknown> = {
    ...data,
    series,
    date_range: {
      ...data.date_range,
      start: series[0].date,
      end: series[series.length - 1].date,
      days: series.length,
    },
  };
  if (sp.get("baseline") === "false") delete body.baseline;
  return Response.json(body, {
    headers: {
      "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400",
      "Access-Control-Allow-Origin": "*",
    },
  });
}
"""

ROUTE_SUMMARY = HEADER + """import { summaries } from "__REL__";

export async function GET(request: Request) {
  const sp = new URL(request.url).searchParams;
  const region = sp.get("region") ?? "";
  const season = sp.get("season") ?? "";
  if (sp.has("year") || sp.has("include_partial")) {
    return Response.json(
      { detail: "year and include_partial are not supported by the static export (latest complete season only)." },
      { status: 422 },
    );
  }
  const bySeason = summaries[region];
  if (!bySeason) {
    return Response.json(
      { detail: `Unknown region '${region}'. Known: ${Object.keys(summaries).join(", ")}` },
      { status: 404 },
    );
  }
  const data = bySeason[season];
  if (!data) {
    return Response.json(
      { detail: `Unknown season '${season}'. Use one of: ${Object.keys(bySeason).join(", ")}` },
      { status: 422 },
    );
  }
  return Response.json(data, {
    headers: {
      "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400",
      "Access-Control-Allow-Origin": "*",
    },
  });
}
"""


def rel_import(from_dir: Path, target: Path) -> str:
    rel = os.path.relpath(target, from_dir).replace(os.sep, "/")
    return rel if rel.startswith(".") else "./" + rel


def write_route(path: Path, template: str, data_dir: Path, force: bool) -> str:
    if path.exists() and not force:
        return f"skip (exists, use --force): {path}"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(template.replace("__REL__", rel_import(path.parent, data_dir)))
    return f"wrote {path}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--next-dir", required=True, help="Folder of the Next.js app (contains package.json)")
    ap.add_argument("--force", action="store_true", help="Overwrite existing route.ts files")
    args = ap.parse_args()

    nxt = Path(args.next_dir).expanduser().resolve()
    if not (nxt / "package.json").exists():
        raise SystemExit(f"{nxt} has no package.json. Pass the folder of the Next.js app.")
    app_dir = next((p for p in (nxt / "src" / "app", nxt / "app") if p.is_dir()), None)
    if app_dir is None:
        raise SystemExit("No app/ or src/app/ folder found. This script supports the Next.js App Router.")
    data_dir = app_dir.parent / "climate-data"
    (data_dir / "climate").mkdir(parents=True, exist_ok=True)
    (data_dir / "summary").mkdir(parents=True, exist_ok=True)

    settings, regions = load_settings(), load_regions()
    done: dict[str, list[str]] = {}
    for rid, reg in regions.items():
        try:
            cache = load_cache(settings, rid)
        except CacheMissing as exc:
            print(f"skip {rid}: {exc}")
            continue
        if cache.synthetic:
            print(f"WARNING: {rid} is SYNTHETIC data. Do not deploy this.")
        (data_dir / "climate" / f"{rid}.json").write_text(
            json.dumps(climate.daily_response(cache, reg, settings), separators=(",", ":")))
        done[rid] = []
        for season in reg["seasons"]:
            try:
                out = climate.summarize(cache, reg, season, settings)
            except (KeyError, ValueError) as exc:
                print(f"skip {rid} {season}: {exc}")
                continue
            (data_dir / "summary" / f"{rid}.{season}.json").write_text(json.dumps(out, indent=2))
            done[rid].append(season)
        print(f"exported {rid}: seasons {done[rid]}")
    if not done:
        raise SystemExit("Nothing exported. Run the ingest first (python -m cropwise_climate.ingest).")

    regions_out = {rid: {"name": regions[rid].get("name"), "state": regions[rid].get("state"),
                         "lat": regions[rid]["lat"], "lon": regions[rid]["lon"],
                         "seasons": regions[rid]["seasons"], "seasons_status": regions[rid].get("seasons_status"),
                         "enabled": True} for rid in done}
    (data_dir / "regions.json").write_text(json.dumps(regions_out, indent=2))

    lines = [HEADER.strip(), "/* eslint-disable @typescript-eslint/no-explicit-any */"]
    for rid, seasons in done.items():
        lines.append(f'import {rid}_climate from "./climate/{rid}.json";')
        for s in seasons:
            lines.append(f'import {rid}_{s} from "./summary/{rid}.{s}.json";')
    lines.append('import regionsJson from "./regions.json";')
    lines.append("")
    lines.append("export const regions: Record<string, any> = regionsJson;")
    lines.append("export const climate: Record<string, any> = {")
    lines += [f"  {rid}: {rid}_climate," for rid in done]
    lines.append("};")
    lines.append("export const summaries: Record<string, Record<string, any>> = {")
    for rid, seasons in done.items():
        lines.append(f"  {rid}: {{ " + ", ".join(f"{s}: {rid}_{s}" for s in seasons) + " },")
    lines.append("};")
    (data_dir / "index.ts").write_text("\n".join(lines) + "\n")

    api = app_dir / "api"
    for path, tpl in ((api / "regions" / "route.ts", ROUTE_REGIONS),
                      (api / "climate" / "route.ts", ROUTE_CLIMATE),
                      (api / "climate" / "summary" / "route.ts", ROUTE_SUMMARY)):
        print(write_route(path, tpl, data_dir, args.force))
    print(f"\nData folder: {data_dir}\nNext: cd {nxt} && npm run dev, then open /api/climate/summary?region="
          f"{next(iter(done))}&season=kharif")
    return 0


if __name__ == "__main__":
    sys.exit(main())
